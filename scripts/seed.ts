/**
 * Seeds the model catalogue and a demo admin account.
 *
 *   npm run seed                 # upsert models + create demo admin
 *   npm run seed -- --sql        # (re)generate supabase/seed.sql with the models only
 *
 * Env: NEXT_PUBLIC_SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY,
 *      DEMO_ADMIN_EMAIL (default admin@example.com), DEMO_ADMIN_PASSWORD (default: random, printed once)
 */
import "./load-env";
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { SEED_MODELS } from "../src/lib/models/seed-data";
import { seedCreditsPerRequest } from "../src/lib/credits/pricing";

function modelRows() {
  return SEED_MODELS.map((m) => ({
    slug: m.slug,
    display_name: m.display_name,
    provider: m.provider,
    openrouter_id: m.openrouter_id,
    free_openrouter_id: m.free_openrouter_id ?? null,
    fallback_model_slug: m.fallback_model_slug ?? null,
    tier: m.tier,
    input_price_per_m: m.input_price_per_m,
    output_price_per_m: m.output_price_per_m,
    context_length: m.context_length,
    max_output_tokens: m.max_output_tokens ?? null,
    description: m.description,
    sort_order: m.sort_order,
    active: true,
    est_credits_per_request: m.tier === "frontier" ? seedCreditsPerRequest({ ...m, tier: m.tier }) : 0,
  }));
}

function sqlLiteral(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

function writeSeedSql() {
  const rows = modelRows();
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => sqlLiteral((r as Record<string, unknown>)[c])).join(", ")})`).join(",\n");
  const sql = `-- Generated by \`npm run seed -- --sql\` from src/lib/models/seed-data.ts. Do not edit by hand.
insert into public.models (${cols.join(", ")})
values
${values}
on conflict (slug) do update set
${cols.filter((c) => c !== "slug").map((c) => `  ${c} = excluded.${c}`).join(",\n")};
`;
  writeFileSync("supabase/seed.sql", sql);
  console.log(`Wrote supabase/seed.sql (${rows.length} models).`);
}

async function main() {
  if (process.argv.includes("--sql")) return writeSeedSql();

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error("Set NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (e.g. in .env.local).");
  const db = createClient(url, key, { auth: { persistSession: false } });

  const { error } = await db.from("models").upsert(modelRows(), { onConflict: "slug" });
  if (error) throw error;
  console.log(`Upserted ${SEED_MODELS.length} models.`);

  const email = process.env.DEMO_ADMIN_EMAIL || "admin@example.com";
  const password = process.env.DEMO_ADMIN_PASSWORD || randomBytes(12).toString("base64url");
  const { data: created, error: createErr } = await db.auth.admin.createUser({
    email,
    password,
    email_confirm: true,
    user_metadata: { full_name: "Demo Admin" },
  });
  let userId = created?.user?.id;
  if (createErr) {
    if (!/already|registered|exists/i.test(createErr.message)) throw createErr;
    const { data: list } = await db.auth.admin.listUsers({ perPage: 1000 });
    userId = list.users.find((u) => u.email === email)?.id;
    console.log(`Admin user ${email} already exists. Password unchanged.`);
  } else {
    console.log(`Created admin user ${email} with password: ${password}`);
  }
  if (!userId) throw new Error("Could not find the admin user.");
  const { error: roleErr } = await db.from("profiles").upsert({ id: userId, email, role: "admin", display_name: "Demo Admin" });
  if (roleErr) throw roleErr;
  console.log(`${email} is an admin.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
